from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

from app.schemas.provider import GenerationConfig


class EvaluationRun(BaseModel):
    """
    Schema capturing metadata and aggregate status for an evaluation experiment run.
    """

    run_id: str = Field(..., description="Unique UUID or run identifier.")
    dataset_version: str = Field(..., description="Version identifier of the benchmark dataset used.")
    provider: str = Field(..., description="LLM provider name (e.g., 'openai', 'ollama', 'mock').")
    model: str = Field(..., description="Target model name.")
    prompt_version: Optional[str] = Field(
        default=None, description="Optional prompt version or template identifier."
    )
    configuration: Dict[str, Any] = Field(
        default_factory=dict, description="Generation hyperparameters used during the run."
    )
    started_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when the evaluation run started.",
    )
    completed_at: Optional[datetime] = Field(
        default=None, description="Timestamp when the evaluation run finished."
    )
    status: str = Field(
        default="pending",
        description="Execution status ('pending', 'running', 'completed', 'failed').",
    )
    total_cases: int = Field(default=0, ge=0, description="Total number of test cases in the run.")
    passed_cases: int = Field(default=0, ge=0, description="Count of successfully evaluated cases.")
    failed_cases: int = Field(default=0, ge=0, description="Count of cases that encountered errors.")


class EvaluationResult(BaseModel):
    """
    Schema capturing the outcome of evaluating a single test case.
    """

    run_id: str = Field(..., description="Associated evaluation run identifier.")
    test_case_id: str = Field(..., description="ID of the benchmark test case evaluated.")
    response: Optional[str] = Field(
        default=None, description="Raw text response generated by the LLM."
    )
    latency_ms: float = Field(
        default=0.0, ge=0.0, description="Latency in milliseconds for the generation request."
    )
    input_tokens: Optional[int] = Field(
        default=None, description="Count of prompt/input tokens used."
    )
    output_tokens: Optional[int] = Field(
        default=None, description="Count of generated/output tokens."
    )
    total_tokens: Optional[int] = Field(
        default=None, description="Total token consumption."
    )
    error: Optional[str] = Field(
        default=None, description="Error message if generation failed for this case."
    )
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when the case evaluation completed.",
    )


class EvaluationRunSummary(BaseModel):
    """
    Combined report payload containing run metadata, list of results, and aggregate metrics.
    """

    run: EvaluationRun
    results: List[EvaluationResult]
    avg_latency_ms: float = Field(default=0.0, description="Average latency per test case.")
    total_input_tokens: int = Field(default=0, description="Sum of input tokens across all cases.")
    total_output_tokens: int = Field(default=0, description="Sum of output tokens across all cases.")
    total_tokens: int = Field(default=0, description="Sum of total tokens across all cases.")
